"""Embed only the source-pinned public UJI estimator and its two invented examples."""

import argparse
import hashlib
import io
import json
from pathlib import Path
from zipfile import ZipFile


HERE = Path(__file__).resolve().parent
COMMIT = "833d2b30e5637ca40088c28f8df3b7b1cf4a07a3"
REPOSITORY = "https://github.com/eliminatenoise/NeuroTranslation"
ARCHIVE_PATH = "benchmarks/uji-wrist-emg/UJI-Wrist-Supported-Forearm-Model.zip"
ARCHIVE_HASH = "83535af6aa44220781fd5ec515eb082b9e3dd2551ca80c15afc2956c1c288d46"
EXPECTED = {
    "MODEL-STATE.json": "a6b92d0897d2159b64eb519bf2010d6ccd1c9a79a6cfa8dc4742e1ebeecfae53",
    "SYNTHETIC-RMS.json": "3ac01e983a55c8f2e8406ea97f36f2d33db1fe0849f5e5c19d4c6010f3fdab92",
    "SYNTHETIC-ZERO-RMS.json": "56f0ec33c358a208dbdac1b92ce14910680757d37c836025315021988b7beede",
    "infer_uji.py": "c303a1e82be53b71d5e9c110f3d6efe373a0629c43a9e317dbe7abc8b4036801",
    "uji_model.py": "ebcd7b8f68403bb7bebc73c27a7e23ec888f295d9c3adb3af7fe17a64f6b7c23",
    "README.md": "6aaa905d5b5907130c8498589d152a8e9f4e0c77c8f6a6a9246ff01938c58268",
}
MARKER = "/* PUBLIC_UJI_PAYLOAD */ null"


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def identity(data):
    return {"bytes": len(data), "sha256": sha256(data)}


def read_public_members(archive_bytes):
    if sha256(archive_bytes) != ARCHIVE_HASH:
        raise ValueError("Archive differs from the pinned public UJI estimator ZIP")
    with ZipFile(io.BytesIO(archive_bytes)) as archive:
        prefix = "uji-wrist-estimator-preview/"
        members = {name: archive.read(prefix + name) for name in EXPECTED}
        manifest = json.loads(archive.read(prefix + "MANIFEST.json"))
    for name, data in members.items():
        actual = identity(data)
        if actual["sha256"] != EXPECTED[name] or actual != manifest["files"][name]:
            raise ValueError(f"Published member does not match manifest and pin: {name}")
    return members, manifest


def build(archive_bytes):
    members, manifest = read_public_members(archive_bytes)
    source = {
        "repository": REPOSITORY,
        "commit": COMMIT,
        "model_archive_path": ARCHIVE_PATH,
        "model_archive_sha256": ARCHIVE_HASH,
        "model_sha256": EXPECTED["MODEL-STATE.json"],
        "dataset": "https://doi.org/10.5281/zenodo.3469380",
        "data_licence": "https://creativecommons.org/licenses/by/4.0/",
        "glossary_revision": manifest["glossary"]["revision"],
        "glossary_sha256": manifest["glossary"]["sha256"],
    }
    payload = {
        "source": source,
        "model": json.loads(members["MODEL-STATE.json"]),
        "examples": {
            "patterned": json.loads(members["SYNTHETIC-RMS.json"]),
            "zero": json.loads(members["SYNTHETIC-ZERO-RMS.json"]),
        },
    }
    source_path = HERE / "uji-engine-source.js"
    template = source_path.read_text(encoding="utf-8")
    if template.count(MARKER) != 1:
        raise ValueError("The engine template needs exactly one payload marker")
    encoded = json.dumps(payload, indent=2, ensure_ascii=False, allow_nan=False)
    # JSON is a JavaScript expression here. Prefix subsequent lines for source readability.
    embedded = "\n  ".join(encoded.split("\n"))
    header = (
        "// NeuroTranslation UJI browser estimator. Generated by build_engine.py.\n"
        f"// Fitted state and synthetic examples from {REPOSITORY}/tree/{COMMIT}\n"
        "// Study data by Jarque-Bou, Vergara, Sancho-Bru, Gracia-Ibáñez and Roda-Sales.\n"
        "// KIN-MUS UJI v1.0 (CC BY 4.0) https://doi.org/10.5281/zenodo.3469380\n"
    )
    engine = (header + template.replace(MARKER, embedded)).encode("utf-8")
    proof = {
        "schema_version": 1,
        "source": source,
        "archive": identity(archive_bytes),
        "verified_members": {name: identity(data) for name, data in members.items()},
        "embedded_members": ["MODEL-STATE.json", "SYNTHETIC-RMS.json", "SYNTHETIC-ZERO-RMS.json"],
        "build_sources": {
            "build_engine.py": identity(Path(__file__).read_bytes()),
            "uji-engine-source.js": identity(source_path.read_bytes()),
        },
        "generated": {"uji-engine.js": identity(engine)},
    }
    return {
        "uji-engine.js": engine,
        "BUILD-PROOF.json": (json.dumps(proof, ensure_ascii=False, indent=2) + "\n").encode("utf-8"),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path)
    parser.add_argument("--verify", action="store_true", help="Check local outputs without writing")
    args = parser.parse_args()
    try:
        for name, expected in build(args.archive.read_bytes()).items():
            path = HERE / name
            if args.verify:
                if path.read_bytes() != expected:
                    raise ValueError(f"Generated content differs: {name}")
            else:
                path.write_bytes(expected)
    except (OSError, ValueError) as error:
        parser.error(str(error))


if __name__ == "__main__":
    main()
