"""Build the separate browser adapter from the admitted, frozen TRAIN coefficient file."""

import argparse
import json
from pathlib import Path

from build_engine import ARCHIVE_HASH, COMMIT, EXPECTED, HERE, identity, sha256


CONFIG_HASH = "f026284d057a8a5683ef55a4916492ae17d58181b842aefee8c43c9581757eaf"
PYTHON_REFERENCE_HASH = "ec13b01ebc6d1c2a77f37186964416f857084f92cfe9cbbf7b36a82c1deebb01"
MARKER = "/* UJI_AXIS_BLEND_SPEC */ null"
AXES = ["extension_deg", "radial_deviation_deg"]


def read_config(content):
    if sha256(content) != CONFIG_HASH:
        raise ValueError("Blend configuration differs from the frozen TRAIN coefficient file")
    config = json.loads(content)
    if (type(config["schema_version"]) is not int
            or config["schema_version"] != 1
            or config["axes"] != AXES
            or config["base_model_sha256"] != EXPECTED["MODEL-STATE.json"]
            or config["base_archive_sha256"] != ARCHIVE_HASH
            or config["target_offset_ms"] != 250
            or config["amplitude_scale"] != "kin-mus-uji-v1.0-native-amplitude"
            or config["output_units"] != "degrees"):
        raise ValueError("Blend configuration disagrees with the pinned UJI input/output contract")
    alpha = config["alpha"]
    if (not isinstance(alpha, list) or len(alpha) != len(AXES)
            or any(type(value) not in (float, int) or not 0 <= value <= 1 for value in alpha)):
        raise ValueError("Expected two finite blend coefficients from 0 to 1")
    return config


def build(content):
    config = read_config(content)
    source = HERE / "uji-axis-blend-source.js"
    template = source.read_text(encoding="utf-8")
    if template.count(MARKER) != 1:
        raise ValueError("The blend template needs exactly one coefficient marker")
    spec = {**config, "config_sha256": sha256(content)}
    encoded = "\n  ".join(json.dumps(spec, indent=2, allow_nan=False).split("\n"))
    header = "// NeuroTranslation UJI axis blend. Generated by build_axis_blend.py.\n"
    script = (header + template.replace(MARKER, encoded)).encode("utf-8")
    proof = {
        "schema_version": 1,
        "base_public_release_commit": COMMIT,
        "config": identity(content),
        "config_fields": config,
        "python_reference_sha256": PYTHON_REFERENCE_HASH,
        "build_sources": {
            "build_axis_blend.py": identity(Path(__file__).read_bytes()),
            "build_engine.py": identity((HERE / "build_engine.py").read_bytes()),
            "uji-axis-blend-source.js": identity(source.read_bytes()),
        },
        "generated": {"uji-axis-blend.js": identity(script)},
    }
    return {
        "uji-axis-blend.js": script,
        "BUILD-AXIS-BLEND-PROOF.json": (json.dumps(proof, indent=2) + "\n").encode("utf-8"),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("config", type=Path)
    parser.add_argument("--verify", action="store_true", help="Check local outputs without writing")
    args = parser.parse_args()
    try:
        for name, content in build(args.config.read_bytes()).items():
            path = HERE / name
            if args.verify:
                if path.read_bytes() != content:
                    raise ValueError(f"Generated content differs: {name}")
            else:
                path.write_bytes(content)
    except (OSError, ValueError) as error:
        parser.error(str(error))


if __name__ == "__main__":
    main()
