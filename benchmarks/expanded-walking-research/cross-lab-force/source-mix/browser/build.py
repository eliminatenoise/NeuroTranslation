"""Generate the hosted and downloadable single-file force forecast."""

import argparse
from base64 import b64encode
from hashlib import sha256
import json
from pathlib import Path

import numpy as np


HERE = Path(__file__).resolve().parent
PACKAGE = HERE.parent
ROOT = HERE.parents[4]
STUDY_URL = (
    "https://github.com/eliminatenoise/NeuroTranslation/blob/main/"
    "benchmarks/expanded-walking-research/cross-lab-force/source-mix/"
)
PINS = {
    "weights.npz": "0485d6f550c7c2b30f164e776aa8cb87cb5c4dd452340d2f0bf3cccb77e2a0d8",
    "results.json": "9cef501e093a4ae92a51b857ecc47d0c953aa1ea0ff47408206afe98cb2808be",
    "dijon/results.json": "030ad2eced7b937c0b5c08e587dc2c0d390e88bbfd2026d825c8efe962582349",
}


def read_inputs():
    for name, expected in PINS.items():
        payload = (PACKAGE / name).read_bytes()
        assert sha256(payload).hexdigest() == expected, name
    weights = {}
    with np.load(PACKAGE / "weights.npz", allow_pickle=False) as archive:
        for name in archive.files:
            original = archive[name]
            assert original.dtype.name in ("float32", "float64") and np.isfinite(original).all()
            numeric = np.asarray(original, dtype=original.dtype.newbyteorder("<"), order="C")
            weights[name] = {"dtype": original.dtype.name, "shape": list(original.shape),
                             "little_endian_base64": b64encode(numeric.tobytes()).decode("ascii")}
    earlier = json.loads((PACKAGE / "results.json").read_bytes())["cohorts"]
    dijon = json.loads((PACKAGE / "dijon/results.json").read_bytes())["compared_methods"]
    groups = {
        "dijon_loaded": dijon["past_mean_at_least_20_N"],
        "dijon_low": dijon["past_mean_under_20_N"],
        "dijon_all": dijon["all"],
        "treadmill": earlier["external_treadmill"],
        "mixed_lab": earlier["held_force_and_watch"],
    }
    cohorts = {name: {"rows": row["rows"], "people": row["people"], "errors": row["mean_absolute_error_ns"]}
               for name, row in groups.items()}
    return {"weights": weights, "cohorts": cohorts, "source_sha256": PINS,
            "model_commit": "9b92d2133db2eb626e81b72215635e5c43e0082d",
            "dijon_commit": "88860a92b05570c8ac30e9ae395edbcb61fa4eab"}


def render():
    page = (HERE / "page.html").read_text(encoding="utf-8")
    replacements = {
        "@@SIMPLE@@": STUDY_URL + "SIMPLE.md",
        "@@TECHNICAL@@": STUDY_URL + "TECHNICAL.md",
        "@@DIJON@@": STUDY_URL + "dijon/SIMPLE.md",
        "@@STYLE@@": (HERE / "style.css").read_text(encoding="utf-8"),
        "@@ENGINE@@": (HERE / "forecast.mjs").read_text(encoding="utf-8"),
        "@@APP@@": (HERE / "app.js").read_text(encoding="utf-8"),
        "@@DATA@@": json.dumps(read_inputs(), separators=(",", ":"), allow_nan=False).replace("<", "\\u003c"),
    }
    for marker, replacement in replacements.items():
        assert marker in page, marker
        page = page.replace(marker, replacement)
    return page.encode("utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare the generated bytes with the checked-in page.")
    args = parser.parse_args()
    destination = ROOT / "docs/force-forecast/index.html"
    expected = render()
    if args.check:
        assert destination.read_bytes() == expected, "Build the force forecast page from its sources."
    else:
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(expected)
