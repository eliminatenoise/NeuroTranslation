"""Fixed invented angles and positive RMS amplitudes for a software check."""
import json
import math

def make():
    bins = []
    for j in range(16):
        t = (j-15)/16
        bins.append([round(7*t + .8*math.sin(4*t), 5), round(-1.5*t + .4*math.sin(2*t), 5),
                     round(12+3*math.cos(j/4), 5), round(15+4*math.sin(j/5), 5),
                     round(20-2*math.cos(j/3), 5), round(10+5*math.sin(j/4), 5)])
    return {"description": "Wholly invented angles and forearm amplitudes, generated by forearm/make_example.py.",
            "domain":"wrist_angle", "mode":"emg", "forearm_residual":"emg", "slot":[2],
            "anchor_deg":[[10.,-2.]], "bins":[bins]}

if __name__=="__main__":
    print(json.dumps(make(), indent=2))
